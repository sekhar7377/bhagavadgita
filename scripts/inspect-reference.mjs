import { chromium } from '@playwright/test';
import { writeFile, mkdir } from 'node:fs/promises';
const out=process.env.REFERENCE_OUTPUT || '/workspace/reference-study/replay';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',proxy:{server:process.env.HTTPS_PROXY || process.env.HTTP_PROXY},args:['--no-sandbox','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1150,height:720}});
const page=await context.newPage();
const requests=[];const errors=[];
page.on('requestfailed',r=>errors.push({url:r.url(),error:r.failure()?.errorText}));
page.on('pageerror',e=>errors.push({pageError:e.message}));
page.on('response',r=>{if(/\.(js|glb|png|jpg|webp|woff)/.test(r.url())) requests.push({url:r.url(),status:r.status()});});
try {
 await page.goto('https://immersive-g.com/',{waitUntil:'domcontentloaded',timeout:45000});
 console.log('Loaded: '+await page.title());
 await page.locator('.introLoader.main').waitFor({state:'attached',timeout:30000});
 console.log('Hydrated loader attached; awaiting exit');
 await page.waitForFunction(() => {
   const loader = document.querySelector('.introLoader.main');
   const background = loader?.querySelector('.introLoader__bg');
   const word = loader?.querySelector('.introLoader__baseline > div');
   return loader && !loader.classList.contains('lockScroll') && background && word && Number(getComputedStyle(background).opacity) < 0.01 && Number(getComputedStyle(word).opacity) < 0.01;
 }, undefined, {timeout:60000});
 console.log('Loader exit complete');
 console.log((await page.locator('body').innerText()).slice(0,5000));
 await page.screenshot({path:out+'/00-opening.png',timeout:30000});
 console.log('Opening screenshot saved');
 await writeFile(out+'/page.html',await page.content());
 console.log('Links '+JSON.stringify(await page.locator('a').evaluateAll(els=>els.slice(0,30).map(e=>({text:e.textContent,href:e.getAttribute('href')})))));
 await page.mouse.move(180,350);await page.waitForTimeout(1000);
 await page.mouse.move(950,350,{steps:18}); await page.waitForTimeout(300);
 await page.screenshot({path:out+'/01-slow-sweep.png',timeout:30000});
 await page.waitForTimeout(2500);await page.screenshot({path:out+'/02-stationary.png',timeout:30000});
 await page.mouse.move(250,180,{steps:5});await page.screenshot({path:out+'/03-fast-stroke.png',timeout:30000});
 await page.mouse.move(1149,719);await page.mouse.move(1155,730);await page.waitForTimeout(4000);
 await page.screenshot({path:out+'/04-exit-after-four-seconds.png',timeout:30000});
 await page.mouse.wheel(0,800);await page.waitForTimeout(2000);
 await page.screenshot({path:out+'/05-scroll.png',timeout:30000});
 console.log('Motion sequence captured');
} catch(e){console.log('FAIL '+e.stack);}
await writeFile(out+'/requests.json',JSON.stringify(requests,null,2));
await writeFile(out+'/errors.json',JSON.stringify(errors,null,2));
await context.close();await browser.close();
